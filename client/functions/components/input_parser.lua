InputParser.InputPattern = "~(INPUT_[A-Z_]+)~"

function InputParser.ParseInputs(text)
    if not text or type(text) ~= "string" then return text end
    return string.gsub(text, InputParser.InputPattern, function(inputName)
        local label = InputParser.InputMappings[inputName]
        if label and label ~= "(None)" then
            return '<span class="keybind">' .. label .. '</span>'
        else
            return '<span class="keybind">' .. inputName .. '</span>'
        end
    end)
end

